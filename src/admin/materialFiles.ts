import type { AdminData, Material } from './types'

/**
 * Material files in the prototype. Only a file's name and size are stored, not its contents,
 * so a download hands over a sample file: the bundled deck for presentations, or a generated
 * PDF copy for documents. Videos and links open their source instead (videos never download).
 */

export const formatBytes = (bytes?: number) =>
  bytes == null ? '' : bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))} KB` : `${(bytes / (1024 * 1024)).toFixed(1)} MB`

/** File name shown for a material; falls back to one made from its title. */
export function materialFileName(m: Material) {
  if (m.fileName) return m.fileName
  const ext = m.type === 'PRESENTATION' ? 'pptx' : 'pdf'
  return `${m.title.replace(/[\\/:*?"<>|]+/g, ' ').trim()}.${ext}`
}

export const canDownloadFile = (m: Material) => m.type === 'DOCUMENT' || m.type === 'PRESENTATION'

function save(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  Object.assign(document.createElement('a'), { href: url, download: name }).click()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** Downloads (or, for videos and links, opens) a material. Returns false when there was nothing to open. */
export async function downloadMaterial(m: Material): Promise<boolean> {
  if (!canDownloadFile(m)) {
    if (!m.url) return false
    window.open(m.url, '_blank', 'noopener')
    return true
  }
  const name = materialFileName(m)
  if (m.type === 'PRESENTATION' || name.toLowerCase().endsWith('.pptx')) {
    const res = await fetch('/trainings/Sample Training.pptx')
    save(await res.blob(), name.toLowerCase().endsWith('.pptx') ? name : `${name}.pptx`)
    return true
  }
  const { jsPDF } = await import('jspdf')
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' })
  pdf.setFont('helvetica', 'bold').setFontSize(18).text(m.title, 20, 28, { maxWidth: 170 })
  pdf.setFont('helvetica', 'normal').setFontSize(10).setTextColor(110).text(`M-PESA Academy · version ${m.version} · updated ${m.updatedAt}`, 20, 40)
  pdf.setFontSize(12).setTextColor(30).text(m.description || 'No description.', 20, 54, { maxWidth: 170 })
  pdf.setFontSize(9).setTextColor(150).text('Demo copy generated by the prototype — the original file is not stored.', 20, 285)
  save(pdf.output('blob'), name.toLowerCase().endsWith('.pdf') ? name : `${name}.pdf`)
  return true
}

/** Adds one download to the material's counters used by reports. */
export const countDownload = (d: AdminData, id: string): AdminData => ({
  ...d,
  contentStats: { ...d.contentStats, [id]: { views: d.contentStats[id]?.views ?? 0, downloads: (d.contentStats[id]?.downloads ?? 0) + 1 } },
})
